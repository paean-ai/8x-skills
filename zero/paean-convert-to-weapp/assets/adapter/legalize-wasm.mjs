// Build-time interface conversion. Internal layout math remains i64.
export function legalizeI64(binaryen,bytes){
  const module=binaryen.readBinary(bytes);
  function signatures(){
    const abi={imports:[],exports:[]};
    const signature=f=>{
      const params=binaryen.expandType(f.params).map(t=>t===binaryen.i64?'i64':t===binaryen.i32?'i32':t===binaryen.f64?'f64':t===binaryen.f32?'f32':String(t));
      return params.includes('i64')||f.results===binaryen.i64?{params,result:f.results===binaryen.i64?'i64':'other'}:null;
    };
    for(let i=0;i<module.getNumFunctions();i++){
      const f=binaryen.getFunctionInfo(module.getFunctionByIndex(i)),s=signature(f);
      if(f.module&&s)abi.imports.push({module:f.module,name:f.base,...s});
    }
    for(let i=0;i<module.getNumExports();i++){
      const e=binaryen.getExportInfo(module.getExportByIndex(i));if(e.kind!==binaryen.ExternalFunction)continue;
      const s=signature(binaryen.getFunctionInfo(module.getFunction(e.value)));
      if(s)abi.exports.push({name:e.name,...s});
    }
    return abi;
  }
  try{
    const abi=signatures();
    // This pinned binding returns u64 values through memory. If that changes,
    // implement and test the tempRet0 return ABI before accepting a new pin.
    if([...abi.imports,...abi.exports].some(e=>e.result==='i64'))throw new Error('Review i64 return ABI before upgrading the pinned layout binding');
    module.runPasses(['legalize-js-interface']);
    const after=signatures();
    if(after.imports.length||after.exports.length||!module.validate())throw new Error('i64 still crosses the native JS/WASM boundary');
    return {abi,wasm:module.emitBinary()};
  }finally{module.dispose();}
}
export function bridgeBinding(source){
  for(const [from,to]of [['return imports;','return adaptI64Imports(imports);'],['wasm = instance.exports;','wasm = adaptI64Exports(instance.exports);']]){
    if(source.split(from).length!==2)throw new Error('Pinned binding changed; review the i64 bridge');
    source=source.replace(from,to);
  }
  return "// Generated by wasm-bindgen; i64 ABI bridge applied by rebuild-taffy.mjs.\nimport {adaptI64Imports,adaptI64Exports} from '../../wasm-abi.js';\n"+source;
}
